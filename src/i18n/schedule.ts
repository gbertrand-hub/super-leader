function interpolate(template: string, values?: Values) {
  if (!values) return template;
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

export function scheduleText(locale: string, key: string, values?: Values) {
  const normalizedKey = key.startsWith("schedule.") ? key.slice("schedule.".length) : key;
  const dictionary = locale === "fr" ? fr : en;
  return interpolate(dictionary[normalizedKey] ?? `schedule.${normalizedKey}`, values);
}
