export function getCrmPipelineText(locale: string) {
  return dictionaries[(locale === "en" ? "en" : "fr") as Locale];
}

export function sectorFieldLabels(locale: string, sector: CrmSector) {
  const copy = getCrmPipelineText(locale);
  const fields = (copy.sectorFields as unknown as Record<string, readonly string[]>)[sector];
  if (fields?.length) return [...fields];
  return locale === "en"
    ? ["Primary need", "Budget / capacity", "Preference", "Additional information"]
    : ["Besoin principal", "Budget / capacité", "Préférence", "Information complémentaire"];
}

export function sectorLabel(locale: string, sector: CrmSector) {
  const labels: Record<string, Record<string, string>> = {
    fr: {house: "Maisons", land: "Terrains", training: "Formations", livestock: "Élevage", vip: "Super Leader VIP"},
    en: {house: "Houses", land: "Land", training: "Training", livestock: "Livestock", vip: "Super Leader VIP"},
  };
  const language = locale === "en" ? "en" : "fr";
  const known = labels[language][sector];
  if (known) return known;
  return String(sector || "")
    .replace(/[_-]+/g, " ")
    .replace(/\b\w/g, (letter) => letter.toUpperCase());
}

